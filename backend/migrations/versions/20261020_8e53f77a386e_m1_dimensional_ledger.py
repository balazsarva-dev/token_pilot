# Computed vs billed per tenant, provider and day. Only token line items are compared:
# tool calls, web search etc. have no token usage to compute from.
# Differences are calculated here, never stored (they would go stale after re-pricing).
DAILY_RECONCILIATION_VIEW = """
CREATE VIEW daily_reconciliation AS
WITH computed AS (
    SELECT tenant_id, provider, date_key,
           SUM(computed_cost)                               AS computed_usd,
           COUNT(*) FILTER (WHERE computed_cost IS NULL)    AS unpriced_rows
    FROM fct_usage
    GROUP BY tenant_id, provider, date_key
),
billed AS (
    SELECT tenant_id, provider, date_key, SUM(amount_usd) AS billed_usd
    FROM fct_billed_cost
    WHERE token_type IS NOT NULL
    GROUP BY tenant_id, provider, date_key
)
SELECT tenant_id,
       provider,
       d.date,
       c.computed_usd,
       b.billed_usd,
       c.computed_usd - b.billed_usd                                   AS diff_usd,
       ROUND((c.computed_usd - b.billed_usd) / NULLIF(b.billed_usd, 0) * 100, 2) AS diff_pct,
       COALESCE(c.unpriced_rows, 0)                                    AS unpriced_rows
FROM computed c
FULL JOIN billed b USING (tenant_id, provider, date_key)
JOIN dim_date d USING (date_key)
"""


