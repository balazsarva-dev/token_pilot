import { useCallback, useEffect, useState } from "react";

import { type Audit, getAudit } from "./api.ts";
import { AuditReport } from "./AuditReport.tsx";
import { SyncBar } from "./Sync.tsx";
import { Upload } from "./Upload.tsx";

type State =
  | { status: "loading" }
  | { status: "empty" }
  | { status: "ready"; audit: Audit; isExample: boolean }
  | { status: "error"; message: string };

export function App() {
  const [showSmall, setShowSmall] = useState(false);
  const [state, setState] = useState<State>({ status: "loading" });
  const [version, setVersion] = useState(0);
  const reload = useCallback(() => setVersion((v) => v + 1), []);

  useEffect(() => {
    let cancelled = false;
    async function load(): Promise<State> {
      const own = await getAudit("local", showSmall);
      if (own) return { status: "ready", audit: own, isExample: false };
      const example = await getAudit("demo", showSmall);
      return example ? { status: "ready", audit: example, isExample: true } : { status: "empty" };
    }
    load()
      .then((next) => {
        if (!cancelled) setState(next);
      })
      .catch((error: Error) => {
        if (!cancelled) setState({ status: "error", message: error.message });
      });
    return () => {
      cancelled = true;
    };
  }, [showSmall, version]);

  const showWelcome = state.status === "empty" || (state.status === "ready" && state.isExample);

  return (
    <>
      <Header />
      <main className="mx-auto max-w-[1180px] px-4 pb-24 sm:px-6">
        <SyncBar tenant="local" onSynced={reload} />

        {state.status === "loading" && <p className="py-24 text-text-3">Loading…</p>}

        {state.status === "error" && (
          <div className="mt-12 rounded-2xl border border-hairline bg-tint p-8">
            <h1 className="text-2xl font-extrabold">The audit could not be loaded</h1>
            <p className="mt-2 text-text-2">
              Is the API running? Start it with <code className="num">make run</code>.
            </p>
            <p className="num mt-4 text-sm text-text-3">{state.message}</p>
          </div>
        )}

        {showWelcome && <Welcome onImported={reload} />}

        {state.status === "ready" && (
          <>
            {state.isExample && <ExampleBanner />}
            <AuditReport
              audit={state.audit}
              isDemo={state.isExample}
              showSmall={showSmall}
              onShowSmall={setShowSmall}
            />
            {!state.isExample && (
              <section className="mt-20">
                <h2 className="text-[26px] font-extrabold">Add or replace exports</h2>
                <p className="mt-2 max-w-[65ch] text-text-2">
                  Uploading a newer export of the same days updates them; nothing is counted twice.
                </p>
                <div className="mt-6">
                  <Upload tenant="local" onImported={reload} onDeleted={reload} />
                </div>
              </section>
            )}
          </>
        )}
      </main>
    </>
  );
}

function Header() {
  return (
    <header className="sticky top-0 z-10 border-b border-hairline bg-ink/80 backdrop-blur">
      <div className="mx-auto flex h-16 max-w-[1180px] items-center px-4 sm:px-6">
        <div className="flex items-center gap-3">
          <span className="grid size-8 place-items-center rounded-lg bg-amber text-sm font-extrabold text-ink">
            T
          </span>
          <span className="font-semibold">TokenPilot</span>
          <span className="hidden text-sm text-text-3 sm:inline">AI bill audit</span>
        </div>
      </div>
    </header>
  );
}

function ExampleBanner() {
  return (
    <div className="mt-6 rounded-xl border border-hairline bg-tint px-5 py-3 text-sm text-text-2">
      <strong className="text-text-1">Example report.</strong> Synthetic usage generated by
      TokenPilot to show what an audit finds. Your numbers will vary.
    </div>
  );
}

function Welcome({ onImported }: { onImported: () => void }) {
  return (
    <section className="py-16">
      <h1 className="max-w-[18ch] text-[36px] leading-[1.08] font-extrabold tracking-[-0.02em] md:text-[46px]">
        Find what your AI bill is <span className="text-amber">wasting</span>
      </h1>
      <p className="mt-5 max-w-[60ch] text-[17px] leading-relaxed text-text-2">
        Upload your OpenAI and Anthropic usage exports and get concrete, dollar-quantified savings,
        each with the reasoning behind it. No access to your accounts needed.
      </p>
      <div className="mt-10">
        <Upload tenant="local" onImported={onImported} onDeleted={onImported} />
      </div>
    </section>
  );
}
